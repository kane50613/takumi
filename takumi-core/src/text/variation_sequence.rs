#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn sequences_of_each_kind() {
    assert!(is_variation_sequence('\u{203C}', VARIATION_SELECTOR_16));
    assert!(is_variation_sequence('\u{203C}', VARIATION_SELECTOR_15));
    assert!(!is_variation_sequence('a', VARIATION_SELECTOR_16));
    assert!(is_variation_sequence('0', '\u{FE00}'));
    assert!(!is_variation_sequence('1', '\u{FE00}'));
    assert!(is_variation_sequence('\u{845B}', '\u{E0100}'));
    assert!(!is_variation_sequence('\u{F900}', '\u{E0100}'));
    assert!(is_variation_sequence('\u{FA0E}', '\u{E0100}'));
  }

  #[test]
  fn selectors() {
    assert!(is_unicode_variation_selector('\u{180C}'));
    assert!(!is_unicode_variation_selector('\u{180F}'));
    assert!(is_unicode_variation_selector(VARIATION_SELECTOR_16));
    assert!(is_unicode_variation_selector('\u{E01EF}'));
  }
}
