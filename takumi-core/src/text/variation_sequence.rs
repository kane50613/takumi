//! Blink's [`character_variation_sequences.cc`](https://source.chromium.org/chromium/chromium/src/+/main:third_party/blink/renderer/platform/text/character_variation_sequences.cc).

use std::ops::RangeInclusive;

use icu_properties::{CodePointSetData, props::Ideographic};

use crate::text::character::{VARIATION_SELECTOR_15, VARIATION_SELECTOR_16, is_emoji};

/// Blink's `IsUnicodeVariationSelector`.
pub(crate) fn is_unicode_variation_selector(character: char) -> bool {
  matches!(
    character,
    '\u{180B}'..='\u{180D}' | '\u{FE00}'..='\u{FE0F}' | '\u{E0100}'..='\u{E01EF}'
  )
}

/// Blink's `IsVariationSequence`.
pub(crate) fn is_variation_sequence(character: char, selector: char) -> bool {
  is_emoji_variation_sequence(character, selector)
    || is_standardized_variation_sequence(character, selector)
    || is_ideographic_variation_sequence(character, selector)
}

/// Blink's `IsEmojiVariationSequence`.
fn is_emoji_variation_sequence(character: char, selector: char) -> bool {
  matches!(selector, VARIATION_SELECTOR_15 | VARIATION_SELECTOR_16) && is_emoji(character)
}

/// Blink's `IsStandardizedVariationSequence`, over its copy of
/// <https://www.unicode.org/Public/UNIDATA/StandardizedVariants.txt>.
fn is_standardized_variation_sequence(character: char, selector: char) -> bool {
  let selector = match selector {
    '\u{FE00}'..='\u{FE0D}' => u32::from(selector) - 0xFE00,
    '\u{180B}'..='\u{180F}' => u32::from(selector) - 0x180B + 16,
    _ => return false,
  };

  STANDARDIZED_VARIATION_SEQUENCES
    .binary_search(&(u32::from(character) << 5 | selector))
    .is_ok()
}

/// Blink's `IsIdeographicVariationSequence` (UTS #37): an ideograph that decomposes neither
/// canonically nor compatibly, then a selector from U+E0100 to U+E01EF.
fn is_ideographic_variation_sequence(character: char, selector: char) -> bool {
  ('\u{E0100}'..='\u{E01EF}').contains(&selector)
    && CodePointSetData::new::<Ideographic>().contains(character)
    && !DECOMPOSABLE_IDEOGRAPHS
      .iter()
      .any(|range| range.contains(&u32::from(character)))
}

